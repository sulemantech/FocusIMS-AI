/**
 * Helper to retrieve a source record reference for clickable drawer modals
 */
export function getSourceRecordById(id: string): SourceRecordRef | null {
  const cleanId = id.trim().toUpperCase();

  // Incident
  const inc = INITIAL_INCIDENTS.find(i => i.id === cleanId);
  if (inc) {
    return {
      id: inc.id,
      type: 'incident',
      title: inc.title,
      status: inc.status,
      risk: inc.risk,
      owner: inc.owner,
      site: inc.site,
    };
  }

  // Risk
  const rsk = INITIAL_RISKS.find(r => r.id === cleanId);
  if (rsk) {
    return {
      id: rsk.id,
      type: 'risk',
      title: rsk.title,
      status: rsk.isReviewOverdue ? 'Review Overdue' : 'Active',
      risk: rsk.residualRisk,
      owner: rsk.owner,
      site: rsk.site,
    };
  }

  // Action
  const act = INITIAL_ACTIONS.find(a => a.id === cleanId);
  if (act) {
    return {
      id: act.id,
      type: 'action',
      title: act.action,
      status: act.status,
      risk: act.priority === 'High' ? 'High' : act.priority === 'Medium' ? 'Medium' : 'Low',
      owner: act.owner,
      site: act.site,
    };
  }

  // Training
  const tr = INITIAL_TRAINING.find(t => t.id === cleanId);
  if (tr) {
    return {
      id: tr.id,
      type: 'training',
      title: `${tr.employeeName} - ${tr.certification}`,
      status: tr.status,
      owner: tr.employeeName,
      site: tr.site,
    };
  }

  // Audit
  const aud = INITIAL_AUDITS.find(a => a.id === cleanId);
  if (aud) {
    return {
      id: aud.id,
      type: 'audit',
      title: aud.title,
      status: aud.status,
      owner: aud.leadAuditor,
    };
  }

  // Document
  const doc = INITIAL_DOCUMENTS.find(d => d.id === cleanId);
  if (doc) {
    return {
      id: doc.id,
      type: 'document',
      title: doc.title,
      status: doc.status,
      owner: doc.owner,
    };
  }

  return null;
}

